"""Question 108: the invariant modulus of every positional system, computed.

For a numeration system, group the integers N of a range by the multiset of
their digits and compute the gcd of all differences N - N' inside a group.
Propositions 35.5 and 35.6 of docs/library/35-existence.md predict it:
the integers in the ideal generated by (x - y)(beta_i - beta_j) over the
exchanges that the system allows.

    python3 r6h_invariant.py > data/r6h_invariant.txt
"""
import math
from collections import defaultdict


def gcd_of_groups(pairs):
    """pairs: iterable of (key, N). gcd of differences within each key."""
    first = {}
    g = 0
    groups = 0
    for key, n in pairs:
        if key in first:
            g = math.gcd(g, n - first[key])
        else:
            first[key] = n
            groups += 1
    return g, groups


def digits_std(n, b):
    out = []
    while n:
        n, r = divmod(n, b)
        out.append(r)
    return out


def digits_neg(n, b):
    """base -b, digits 0..b-1"""
    out = []
    while n:
        r = n % b
        out.append(r)
        n = (n - r) // (-b)
    return out


def digits_bij(n, b):
    """bijective base b, digits 1..b"""
    out = []
    while n:
        r = n % b
        if r == 0:
            r = b
        out.append(r)
        n = (n - r) // b
    return out


def digits_bal(n, b):
    """balanced base b (odd b), digits -(b-1)/2..(b-1)/2"""
    h = (b - 1) // 2
    out = []
    while n:
        r = ((n + h) % b) - h
        out.append(r)
        n = (n - r) // b
    return out


def digits_fact(n):
    out = []
    i = 2
    while n:
        n, r = divmod(n, i)
        out.append(r)
        i += 1
    return out


def digits_ratl(n, p, q):
    """Akiyama-Frougny-Sakarovitch base p/q: q N_i = p N_(i+1) + a_i"""
    out = []
    while n:
        a = (q * n) % p
        out.append(a)
        n = (q * n - a) // p
    return out


def digits_negratl(n, p, q, limit=400):
    """base -p/q: q N_i = -p N_(i+1) + a_i, 0 <= a_i < p. None if no end."""
    out = []
    seen = 0
    while n:
        a = (q * n) % p
        out.append(a)
        n = (a - q * n) // p
        seen += 1
        if seen > limit:
            return None
    return out


def digits_cns(z, n, w):
    """canonical number system base beta = -n + w in Z[w], w = i (w2 = -1) or
    the Eisenstein omega (w2 = -1 - w). z = (a, c) means a + c w."""
    a, c = z
    out = []
    if w == 'i':
        M = n * n + 1
    else:
        M = n * n + n + 1
    steps = 0
    while (a, c) != (0, 0):
        # last digit: a + c w == a + n c (mod beta), since w == n
        d = (a + n * c) % M
        out.append(d)
        a -= d
        # divide (a + c w) by beta = -n + w: multiply by conj and divide by norm
        if w == 'i':
            # (a + c i) / (-n + i) = (a + c i)(-n - i) / M
            ra, rc = -n * a + c, -a - n * c
        else:
            # conj(-n + w) = -n + w^2 = -n - 1 - w ; norm M
            # (a + c w)(-n - 1 - w) = a(-n-1) - a w + c w (-n-1) - c w^2
            #   = a(-n-1) + c + w(-a + c(-n-1) + c)
            ra, rc = a * (-n - 1) + c, -a - c * n
        assert ra % M == 0 and rc % M == 0
        a, c = ra // M, rc // M
        steps += 1
        if steps > 500:
            return None
    return out


def pisot_digits(N, x):
    """greedy expansion of the integer N >= 1 in base eps, eps^2 = x eps + 1.
    Numbers are pairs (u, v) = u + v eps. Returns the digit list."""
    D = x * x + 4

    def ge0(u, v):
        # u + v eps >= 0 with eps = (x + sqrt D)/2  <=>  2u + v x + v sqrt(D) >= 0
        s, t = 2 * u + v * x, v
        if s >= 0 and t >= 0:
            return True
        if s <= 0 and t <= 0:
            return s == 0 and t == 0
        if s > 0:
            return s * s >= t * t * D
        return t * t * D >= s * s

    def pw(k):
        # eps^k as (u, v); eps^-1 = eps - x
        if k >= 0:
            u, v = 1, 0
            for _ in range(k):
                u, v = v, u + x * v
            return u, v
        u, v = 1, 0
        for _ in range(-k):
            u, v = v - x * u, u
        return u, v

    k = 0
    while ge0(*(lambda p: (N - p[0], -p[1]))(pw(k + 1))):
        k += 1
    ru, rv = N, 0
    digs = []
    i = k
    while (ru, rv) != (0, 0):
        pu, pv = pw(i)
        d = 0
        while d < x and ge0(ru - (d + 1) * pu, rv - (d + 1) * pv):
            d += 1
        digs.append(d)
        ru, rv = ru - d * pu, rv - d * pv
        i -= 1
        if i < -200:
            return None
    return digs


def key(digs):
    return tuple(sorted(digs))


def main():
    print("# system parameter: gcd of N - N' over equal digit multisets, groups, prediction")
    for b in range(3, 13):
        g, n = gcd_of_groups((key(digits_std(N, b)), N) for N in range(b * b, b ** 4))
        print(f"base b={b}: {g} ({n} groups), predicted b-1 = {b - 1}")
    for b in range(2, 11):
        g, n = gcd_of_groups((key(digits_neg(N, b)), N) for N in range(-b ** 4, b ** 4) if len(digits_neg(N, b)) >= 3)
        print(f"base -b, b={b}: {g} ({n} groups), predicted b+1 = {b + 1}")
    for b in range(2, 11):
        g, n = gcd_of_groups((key(digits_bij(N, b)), N) for N in range(b + 1, b ** 4))
        print(f"bijective base b={b}: {g} ({n} groups), predicted b-1 = {b - 1}")
    for b in (3, 5, 7, 9):
        g, n = gcd_of_groups((key(digits_bal(N, b)), N) for N in range(-b ** 4, b ** 4) if len(digits_bal(N, b)) >= 3)
        print(f"balanced base b={b}: {g} ({n} groups), predicted b-1 = {b - 1}")
    g, n = gcd_of_groups((key(digits_fact(N)), N) for N in range(1, 50000))
    print(f"factorial system: {g} ({n} groups), predicted 1")
    for p, q in ((3, 2), (5, 2), (5, 3), (7, 2), (7, 3), (7, 4), (7, 5), (8, 3), (9, 4), (10, 3)):
        g, n = gcd_of_groups((key(digits_ratl(N, p, q)), N) for N in range(1, 20000))
        print(f"base {p}/{q}: {g} ({n} groups), predicted p-q = {p - q}")
    for p, q in ((3, 2), (5, 2), (5, 3), (7, 2), (7, 3), (4, 3), (5, 4)):
        rows = []
        bad = 0
        for N in range(-5000, 5000):
            d = digits_negratl(N, p, q)
            if d is None:
                bad += 1
                continue
            rows.append((key(d), N))
        g, n = gcd_of_groups(rows)
        print(f"base -{p}/{q}: {g} ({n} groups, {bad} without a finite expansion), predicted p+q = {p + q}")
    for nn in range(1, 6):
        rows = []
        for N in range(-3000, 3000):
            d = digits_cns((N, 0), nn, 'i')
            if d is not None and len(d) >= 3:
                rows.append((key(d), N))
        g, n = gcd_of_groups(rows)
        print(f"Gaussian base -{nn}+i, rational integers: {g} ({n} groups), predicted (n+1)^2+1 = {(nn + 1) ** 2 + 1}")
    for nn in range(1, 5):
        rows = []
        for N in range(-3000, 3000):
            d = digits_cns((N, 0), nn, 'w')
            if d is not None and len(d) >= 3:
                rows.append((key(d), N))
        g, n = gcd_of_groups(rows)
        print(f"Eisenstein base -{nn}+omega, rational integers: {g} ({n} groups), predicted n^2+3n+3 = {nn * nn + 3 * nn + 3}")
    for x in range(1, 9):
        rows = []
        bylen = defaultdict(list)
        for N in range(1, 6000):
            d = pisot_digits(N, x)
            if d is None:
                continue
            rows.append((key(d), N))
            bylen[len(d)].append((key(d), N))
        g, n = gcd_of_groups(rows)
        per = sorted({gcd_of_groups(v)[0] for v in bylen.values() if len(v) > 1} - {0})
        print(f"Pisot base eps_{x}: {g} ({n} groups), predicted x = {x}; gcds within one length: {per}")


if __name__ == '__main__':
    main()
